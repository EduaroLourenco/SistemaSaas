import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { createRequire } from 'node:module';

// Executa os módulos de produção; não copia a regra para dentro do teste.
const pasta=mkdtempSync(join(tmpdir(),'gerizo-central-'));
try {
  for (const nome of ['analise','central-anuncios','periodo-anuncios']) writeFileSync(join(pasta,`${nome}.js`),ts.transpileModule(readFileSync(new URL(`../src/lib/${nome}.ts`,import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText);
  const {prepararAnuncios,pertenceFila,resumoAnuncios,sinalAnuncio}=createRequire(import.meta.url)(join(pasta,'central-anuncios.js'));
  const semana={semana:'S44/26',intervalo:'26/10 – 01/11',visitas:100,vendas:4,receita:400,precoAnunciado:null,precoRealizado:100,precoIdeal:120,comissao:16,tarifaCobrada:null,dias:[],campanhas:[]};
  const anuncio=(mlb,semanas=[],extra={})=>({mlb,sku:'SKU',titulo:'Produto',tipo:'Clássico',status:'ativo',conta:'A',categoria:'Produto',estoque:null,precoAtual:110,semanas,...extra});
  const entrada=[anuncio('MLB1',[semana]),anuncio('MLB2',[{...semana,visitas:200,vendas:0,receita:0,precoRealizado:null}],{estoque:0}),anuncio('MLB3',[],{precoReferencia:120}),anuncio('MLB4',[],{status:'pausado',estoque:0}),anuncio('MLB5',[{...semana,semana:'S1/25'}])];
  const antes=structuredClone(entrada);
  const itens=prepararAnuncios(entrada,['S44/26']);
  const porId=new Map(itens.map(a=>[a.mlb,a]));
  assert.equal(itens.length,5,'Cadastro sem histórico permanece pesquisável');
  assert.equal(porId.get('MLB3').semanas.length,0);
  assert.equal(porId.get('MLB5').semanas.length,0,'Dado de outro período não entra no recorte');
  assert.equal(porId.get('MLB1').metricas.precoVitrine,null,'Preço pago não vira preço de vitrine');
  assert.equal(porId.get('MLB1').metricas.precoPraticado,100);
  assert.equal(pertenceFila(porId.get('MLB3'),'sem_tabela'),false,'Referência do cadastro é válida sem histórico');
  assert.equal(pertenceFila(porId.get('MLB3'),'sem_historico'),true);
  assert.equal(pertenceFila(porId.get('MLB2'),'estoque'),true);
  assert.equal(pertenceFila(porId.get('MLB4'),'estoque'),false,'Fila de ruptura é só para ativos');
  assert.equal(sinalAnuncio(porId.get('MLB4')).texto,'Pausado');
  assert.equal(sinalAnuncio(porId.get('MLB3')).texto,'Sem histórico');
  const semAusentes=prepararAnuncios(entrada.slice(0,2),['S44/26']);
  assert.deepEqual(porId.get('MLB1').lentes,semAusentes[0].lentes,'Ausência de coleta não dilui a média da carteira');
  assert.deepEqual(resumoAnuncios(itens),{receita:400,vendas:4,visitas:300,medidos:2,conversao:4/300*100});
  assert.equal(resumoAnuncios([porId.get('MLB3')]).conversao,null);
  assert.equal(resumoAnuncios(prepararAnuncios(entrada,[])).medidos,0);
  assert.deepEqual(entrada,antes,'Análise não altera os dados de entrada');
  const P=createRequire(import.meta.url)(join(pasta,'periodo-anuncios.js'));
  const hoje='2026-11-05';
  const at=Object.fromEntries(P.atalhosPeriodo(hoje).map(a=>[a.id,[a.de,a.ate]]));
  assert.deepEqual(at['7'],['2026-10-29','2026-11-04'],'Atalho fecha ontem');
  assert.deepEqual(at.mes,['2026-11-01','2026-11-04']);
  assert.deepEqual(at.passado,['2026-10-01','2026-10-31']);
  assert.deepEqual(P.atalhosPeriodo('2026-11-01').find(a=>a.id==='mes').ate,'2026-11-01','Dia 1º não gera período invertido');
  const cmp=(de,ate,m)=>{const r=P.periodoComparado({de,ate},m);return r&&[r.de,r.ate];};
  assert.deepEqual(cmp('2026-10-29','2026-11-04','anterior'),['2026-10-22','2026-10-28'],'Mesmo tamanho, imediatamente antes');
  assert.deepEqual(cmp('2026-10-01','2026-10-31','anterior'),['2026-09-01','2026-09-30'],'Mês cheio contra mês cheio');
  assert.deepEqual(cmp('2026-11-01','2026-11-04','mes'),['2026-10-01','2026-10-04']);
  assert.deepEqual(cmp('2026-03-31','2026-03-31','mes'),['2026-02-28','2026-02-28'],'Fim de mês não transborda');
  assert.deepEqual(cmp('2026-02-01','2026-02-28','ano'),['2025-02-01','2025-02-28']);
  assert.equal(cmp('2026-10-01','2026-10-31','nenhum'),null);
  assert.deepEqual(P.periodoValido('2026-10-31','2026-10-01'),{de:'2026-10-01',ate:'2026-10-31'},'Data trocada se endireita');
  assert.equal(P.periodoValido('2026-02-31','2026-03-01'),null,'Data inexistente recusada');
  assert.equal(P.lerPeriodo({vs:'livre'},hoje).modo,'anterior','Livre sem datas volta ao padrão');
  assert.deepEqual(P.lerPeriodo({},hoje).periodo,{de:'2026-10-06',ate:'2026-11-04'});
  const mov=anuncio('MLB9',[],{precoReferencia:50,movimento:[['2026-10-05',null,5,500],['2026-10-06',10,1,100],['2026-10-07',0,0,0],['2026-11-05',20,2,200]],vitrine:{'2026-10-05':99},tarifas:{'2026-10-05':7}});
  const coleta=P.coletaPorConta([mov]);
  const dia=P.recortarAnuncio(mov,{de:'2026-10-05',ate:'2026-10-07'},coleta);
  assert.deepEqual(dia.semanas.map(s=>s.intervalo),['05/10','06/10','07/10']);
  assert.equal(dia.semanas[0].precoAnunciado,99);
  assert.equal(dia.semanas[0].tarifaCobrada,7);
  const [analisado]=prepararAnuncios([dia],dia.semanas.map(s=>s.semana));
  assert.equal(analisado.metricas.vendas,6);
  assert.equal(analisado.metricas.conversao,10,'Venda de dia sem coleta não infla a conversão');
  assert.equal(resumoAnuncios([analisado]).conversao,10);
  const longo=P.recortarAnuncio(mov,{de:'2026-09-02',ate:'2026-11-05'},coleta);
  assert.deepEqual(longo.semanas.map(s=>s.intervalo),['05/10 – 11/10','02/11 – 05/11'],'Período longo agrupa por semana e corta a ponta');
  const corte=P.recortarAnuncio(mov,{de:'2026-10-07',ate:'2026-11-30'},coleta);
  assert.equal(corte.semanas[0].intervalo,'07/10 – 11/10','Semana cortada no início');
  assert.equal(P.totaisNoPeriodo(mov,{de:'2026-01-01',ate:'2026-01-31'},coleta),null,'Sem movimento é nulo, não zero');
  assert.deepEqual(P.totaisNoPeriodo(mov,{de:'2026-10-05',ate:'2026-10-06'},coleta),{visitas:10,vendas:6,vendasComVisita:1,receita:600});
  assert.equal(P.coletaCompleta(['A'],{de:'2026-10-06',ate:'2026-10-07'},coleta),true);
  assert.equal(P.coletaCompleta(['A'],{de:'2026-10-05',ate:'2026-10-06'},coleta),false);
  console.log('Central de anúncios: cadastro, período, ausências, preços, filtros e totais aprovados.');
} finally {
  if (resolve(pasta).startsWith(resolve(tmpdir())+sep) && pasta.includes('gerizo-central-')) rmSync(pasta,{recursive:true,force:true});
}
